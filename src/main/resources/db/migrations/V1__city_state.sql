CREATE TABLE IF NOT EXISTS cp_cities (id VARCHAR(36) PRIMARY KEY, revision BIGINT NOT NULL, payload LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS cp_tokens (id VARCHAR(36) PRIMARY KEY, definition VARCHAR(128) NOT NULL, location VARCHAR(128) NOT NULL);
CREATE TABLE IF NOT EXISTS cp_delivery (id VARCHAR(36) PRIMARY KEY, player VARCHAR(36) NOT NULL, payload LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS cp_events (id VARCHAR(64) PRIMARY KEY, started BIGINT NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS cp_preferences (player VARCHAR(36) PRIMARY KEY, payload TEXT NOT NULL);
